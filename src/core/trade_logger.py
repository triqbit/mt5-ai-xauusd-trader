from __future__ import annotations

import logging
import time
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, Optional

import numpy as np
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    create_engine,
    event,
    text,
)
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship, sessionmaker
from sqlalchemy.pool import QueuePool

Base = declarative_base()
logger = logging.getLogger(__name__)


class AuditMixin:
    """Audit columns as per DATABASE_STANDARDS.md."""

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    updated_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    is_deleted = Column(Boolean, default=False)


class ModelSignal(Base, AuditMixin):
    """Logs every signal generated by the AI models."""

    __tablename__ = "model_signals"
    __table_args__ = (
        Index("idx_signal_ts_sym", "timestamp", "symbol"),
        Index("idx_signal_alg_ts", "algorithm", "timestamp"),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    symbol = Column(String(20), nullable=False)
    direction = Column(Integer, nullable=False)  # +1 buy, -1 sell, 0 hold
    entry_price = Column(Float, nullable=False)
    stop_loss = Column(Float)
    take_profit = Column(Float)
    lot_size = Column(Float)
    algorithm = Column(String(50))
    confidence = Column(Float)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    # Relationship
    trade = relationship("Trade", back_populates="signal", uselist=False)


class Trade(Base, AuditMixin):
    """Logs every executed trade."""

    __tablename__ = "trades"
    __table_args__ = (
        Index("idx_trade_status_ts", "status", "created_at"),
        Index("idx_trade_sym_ts", "symbol", "created_at"),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    ticket = Column(Integer, unique=True, index=True)
    symbol = Column(String(20), nullable=False)
    direction = Column(Integer, nullable=False)
    entry_price = Column(Float, nullable=False)
    exit_price = Column(Float)
    lot_size = Column(Float, nullable=False)
    pnl = Column(Float, default=0.0)
    drawdown_impact = Column(Float)  # impact on total drawdown
    status = Column(String(20), default="OPEN")  # OPEN, CLOSED, CANCELLED

    signal_id = Column(Integer, ForeignKey("model_signals.id"))
    signal = relationship("ModelSignal", back_populates="trade")


class RiskEvent(Base, AuditMixin):
    """Logs risk management events (rejections, circuit breakers)."""

    __tablename__ = "risk_events"
    __table_args__ = (Index("idx_risk_type_ts", "event_type", "created_at"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    event_type = Column(String(50), nullable=False)
    description = Column(Text)
    symbol = Column(String(20))

    signal_id = Column(Integer, ForeignKey("model_signals.id"), nullable=True)


class PerformanceMetric(Base, AuditMixin):
    """Periodic performance snapshots."""

    __tablename__ = "performance_metrics"
    __table_args__ = (Index("idx_perf_ts", "timestamp"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc))
    sharpe_ratio = Column(Float)
    profit_factor = Column(Float)
    max_drawdown = Column(Float)
    total_trades = Column(Integer)
    win_rate = Column(Float)


class TradeLogger:
    """Enterprise trade logging interface."""

    def __init__(self, db_url: str = "sqlite:///trades.db") -> None:
        # 1. Connection pooling and optimization
        connect_args = {}
        if "sqlite" in db_url:
            connect_args["check_same_thread"] = False

        self.engine = create_engine(
            db_url,
            poolclass=QueuePool,
            pool_size=5,
            max_overflow=10,
            pool_timeout=30,
            pool_recycle=1800,
            connect_args=connect_args,
        )

        # 2. Separate read-only engine for reporting
        read_db_url = db_url
        if "sqlite" in db_url:
            if "uri=true" not in read_db_url:
                separator = "&" if "?" in read_db_url else "?"
                read_db_url += f"{separator}mode=ro&uri=true"
            else:
                if "mode=ro" not in read_db_url:
                    read_db_url = read_db_url.replace("mode=rw", "mode=ro")

        self.read_engine = create_engine(
            read_db_url,
            poolclass=QueuePool,
            pool_size=5,
            max_overflow=10,
            connect_args=connect_args,
        )

        # 3. SQLite Pragmas and Performance Events
        if "sqlite" in db_url:

            @event.listens_for(self.engine, "connect")
            @event.listens_for(self.read_engine, "connect")
            def set_sqlite_pragma(dbapi_connection, connection_record):
                cursor = dbapi_connection.cursor()
                cursor.execute("PRAGMA journal_mode=WAL")
                cursor.execute("PRAGMA synchronous=NORMAL")
                cursor.execute("PRAGMA cache_size=-64000")  # 64MB
                cursor.execute("PRAGMA busy_timeout=5000")
                cursor.close()

        # 4. Query Performance Logging
        @event.listens_for(self.engine, "before_cursor_execute")
        def before_cursor_execute(conn, cursor, statement, parameters, context, executemany):
            context._query_start_time = time.time()

        @event.listens_for(self.engine, "after_cursor_execute")
        def after_cursor_execute(conn, cursor, statement, parameters, context, executemany):
            total_time = (time.time() - context._query_start_time) * 1000
            if total_time > 100:  # Threshold 100ms
                logger.warning("Slow Query: %s | Time: %.2fms", statement, total_time)

        Base.metadata.create_all(self.engine)
        self.Session = sessionmaker(bind=self.engine)
        self.ReadSession = sessionmaker(bind=self.read_engine)

    def log_signal(self, signal_data: Dict[str, Any]) -> int:
        """Log a new model signal and return its ID."""
        with self.Session() as session:
            signal = ModelSignal(
                symbol=signal_data["symbol"],
                direction=signal_data["direction"],
                entry_price=signal_data["entry_price"],
                stop_loss=signal_data.get("stop_loss"),
                take_profit=signal_data.get("take_profit"),
                lot_size=signal_data.get("lot_size"),
                algorithm=signal_data.get("algorithm"),
                confidence=signal_data.get("confidence"),
                timestamp=signal_data.get("timestamp", datetime.now(timezone.utc)),
            )
            session.add(signal)
            session.commit()
            return signal.id

    def log_trade(
        self,
        ticket: int,
        symbol: str,
        direction: int,
        entry_price: float,
        lot_size: float,
        signal_id: Optional[int] = None,
        status: str = "OPEN",
    ) -> int:
        """Log a trade execution."""
        with self.Session() as session:
            trade = Trade(
                ticket=ticket,
                symbol=symbol,
                direction=direction,
                entry_price=entry_price,
                lot_size=lot_size,
                signal_id=signal_id,
                status=status,
            )
            session.add(trade)
            session.commit()
            return trade.id

    def update_trade(
        self,
        ticket: int,
        exit_price: float,
        pnl: Optional[float] = None,
        drawdown_impact: float = 0.0,
    ) -> None:
        """Update a trade when it is closed. Calculates P&L if not provided."""
        with self.Session() as session:
            trade = session.query(Trade).filter(Trade.ticket == ticket).first()
            if trade:
                trade.exit_price = exit_price
                if pnl is not None:
                    trade.pnl = pnl
                else:
                    # Basic P&L calculation: (exit - entry) * direction * lot_size * contract_size
                    # For XAUUSD, contract size is often 100.
                    contract_size = 100
                    trade.pnl = (
                        (exit_price - trade.entry_price)
                        * trade.direction
                        * trade.lot_size
                        * contract_size
                    )
                trade.drawdown_impact = drawdown_impact
                trade.status = "CLOSED"
                session.commit()
            else:
                logger.warning("Trade with ticket %d not found for update.", ticket)

    def get_trade_by_ticket(self, ticket: int) -> Optional[Trade]:
        """Retrieve trade details by ticket ID."""
        with self.Session() as session:
            return session.query(Trade).filter(Trade.ticket == ticket).first()

    def log_risk_event(
        self,
        event_type: str,
        description: str,
        symbol: Optional[str] = None,
        signal_id: Optional[int] = None,
    ) -> None:
        """Log a risk-related event."""
        with self.Session() as session:
            event = RiskEvent(
                event_type=event_type,
                description=description,
                symbol=symbol,
                signal_id=signal_id,
            )
            session.add(event)
            session.commit()

    def read_performance_report(self) -> Dict[str, float]:
        """
        Calculate key performance metrics from closed trades.
        Returns Sharpe Ratio, Profit Factor, and Max Drawdown.
        """
        with self.Session() as session:
            trades = session.query(Trade).filter(Trade.status == "CLOSED").all()
            if not trades:
                return {
                    "sharpe_ratio": 0.0,
                    "profit_factor": 0.0,
                    "max_drawdown": 0.0,
                }

            pnls = np.array([t.pnl for t in trades])

            # Profit Factor
            gross_profit = np.sum(pnls[pnls > 0])
            gross_loss = abs(np.sum(pnls[pnls < 0]))
            profit_factor = gross_profit / gross_loss if gross_loss > 0 else float("inf")

            # Sharpe Ratio (assumes risk-free rate = 0, per-trade returns)
            if len(pnls) > 1:
                avg_ret = np.mean(pnls)
                std_ret = np.std(pnls)
                sharpe = (avg_ret / std_ret * np.sqrt(252)) if std_ret > 0 else 0.0
            else:
                sharpe = 0.0

            # Max Drawdown
            equity_curve = np.cumsum(pnls)
            peak = np.maximum.accumulate(equity_curve)
            drawdown = peak - equity_curve
            max_dd = np.max(drawdown) if len(drawdown) > 0 else 0.0

            metrics = {
                "sharpe_ratio": float(sharpe),
                "profit_factor": float(profit_factor),
                "max_drawdown": float(max_dd),
            }

            # Optionally log these metrics to DB
            metric_record = PerformanceMetric(
                sharpe_ratio=metrics["sharpe_ratio"],
                profit_factor=metrics["profit_factor"],
                max_drawdown=metrics["max_drawdown"],
                total_trades=len(trades),
                win_rate=float(np.sum(pnls > 0) / len(pnls)),
            )
            session.add(metric_record)
            session.commit()

            return metrics

    def vacuum(self) -> None:
        """Perform database VACUUM to reclaim space."""
        with self.engine.connect() as conn:
            conn.execute(text("VACUUM"))
            logger.info("Database VACUUM completed.")

    def analyze(self) -> None:
        """Perform database ANALYZE to update statistics."""
        with self.engine.connect() as conn:
            conn.execute(text("ANALYZE"))
            logger.info("Database ANALYZE completed.")

    def purge_old_data(self, days: int = 30) -> int:
        """
        Delete data older than X days based on retention policy using bulk delete.
        Returns the number of deleted records.
        """
        cutoff_date = datetime.now(timezone.utc) - timedelta(days=days)
        deleted_count = 0

        with self.Session() as session:
            # Delete ModelSignals older than cutoff
            deleted_count += (
                session.query(ModelSignal).filter(ModelSignal.timestamp < cutoff_date).delete()
            )

            # Delete RiskEvents older than cutoff
            deleted_count += (
                session.query(RiskEvent).filter(RiskEvent.created_at < cutoff_date).delete()
            )

            # Delete PerformanceMetrics older than cutoff
            deleted_count += (
                session.query(PerformanceMetric).filter(PerformanceMetric.timestamp < cutoff_date).delete()
            )

            session.commit()
            logger.info("Purged %d old records older than %s", deleted_count, cutoff_date)
            return deleted_count
