from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Any, Dict, Optional, List

import numpy as np
from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    create_engine,
    CheckConstraint,
    select,
)
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    mapped_column,
    relationship,
    sessionmaker,
    Session,
)

logger = logging.getLogger(__name__)


class Base(DeclarativeBase):
    """Base class for SQLAlchemy models."""
    pass


class AuditMixin:
    """Audit columns as per DATABASE_STANDARDS.md."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    created_by: Mapped[Optional[str]] = mapped_column(String(100))
    updated_by: Mapped[Optional[str]] = mapped_column(String(100))
    deleted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    is_deleted: Mapped[bool] = mapped_column(Boolean, default=False)


class ModelSignal(Base, AuditMixin):
    """Logs every signal generated by the AI models."""

    __tablename__ = "model_signals"
    __table_args__ = (
        CheckConstraint("entry_price > 0", name="check_signal_entry_price_positive"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    symbol: Mapped[str] = mapped_column(String(20), nullable=False)
    direction: Mapped[int] = mapped_column(Integer, nullable=False)  # +1 buy, -1 sell, 0 hold
    entry_price: Mapped[float] = mapped_column(Float, nullable=False)
    stop_loss: Mapped[Optional[float]] = mapped_column(Float)
    take_profit: Mapped[Optional[float]] = mapped_column(Float)
    lot_size: Mapped[Optional[float]] = mapped_column(Float)
    algorithm: Mapped[Optional[str]] = mapped_column(String(50))
    confidence: Mapped[Optional[float]] = mapped_column(Float)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc)
    )

    # Relationship
    trade: Mapped[Optional["Trade"]] = relationship("Trade", back_populates="signal", uselist=False)


class Trade(Base, AuditMixin):
    """Logs every executed trade."""

    __tablename__ = "trades"
    __table_args__ = (
        CheckConstraint("entry_price > 0", name="check_trade_entry_price_positive"),
        CheckConstraint("lot_size > 0", name="check_trade_lot_size_positive"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    ticket: Mapped[Optional[int]] = mapped_column(Integer, unique=True, index=True)
    symbol: Mapped[str] = mapped_column(String(20), nullable=False)
    direction: Mapped[int] = mapped_column(Integer, nullable=False)
    entry_price: Mapped[float] = mapped_column(Float, nullable=False)
    exit_price: Mapped[Optional[float]] = mapped_column(Float)
    lot_size: Mapped[float] = mapped_column(Float, nullable=False)
    pnl: Mapped[float] = mapped_column(Float, default=0.0)
    drawdown_impact: Mapped[Optional[float]] = mapped_column(Float)  # impact on total drawdown
    status: Mapped[str] = mapped_column(String(20), default="OPEN")  # OPEN, CLOSED, REJECTED

    signal_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("model_signals.id"))
    signal: Mapped[Optional["ModelSignal"]] = relationship("ModelSignal", back_populates="trade")


class RiskEvent(Base, AuditMixin):
    """Logs risk management events (rejections, circuit breakers)."""

    __tablename__ = "risk_events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    event_type: Mapped[str] = mapped_column(String(50), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text)
    symbol: Mapped[Optional[str]] = mapped_column(String(20))

    signal_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("model_signals.id"))


class PerformanceMetric(Base, AuditMixin):
    """Periodic performance snapshots."""

    __tablename__ = "performance_metrics"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc)
    )
    sharpe_ratio: Mapped[float] = mapped_column(Float)
    profit_factor: Mapped[float] = mapped_column(Float)
    max_drawdown: Mapped[float] = mapped_column(Float)
    total_trades: Mapped[int] = mapped_column(Integer)
    win_rate: Mapped[float] = mapped_column(Float)


class TradeLogger:
    """Enterprise trade logging interface."""

    def __init__(self, db_url: str = "sqlite:///trades.db") -> None:
        self.engine = create_engine(db_url)
        # We rely on Alembic for migrations in production.
        # Base.metadata.create_all(self.engine)
        self.Session = sessionmaker(bind=self.engine)

    def log_signal(self, signal_data: Dict[str, Any], user: str = "system") -> int:
        """Log a new model signal and return its ID."""
        with self.Session() as session:
            signal = ModelSignal(
                symbol=signal_data["symbol"],
                direction=signal_data["direction"],
                entry_price=signal_data["entry_price"],
                stop_loss=signal_data.get("stop_loss"),
                take_profit=signal_data.get("take_profit"),
                lot_size=signal_data.get("lot_size"),
                algorithm=signal_data.get("algorithm"),
                confidence=signal_data.get("confidence"),
                timestamp=signal_data.get("timestamp", datetime.now(timezone.utc)),
                created_by=user,
                updated_by=user,
            )
            session.add(signal)
            session.commit()
            return signal.id

    def log_trade(
        self,
        ticket: Optional[int],
        symbol: str,
        direction: int,
        entry_price: float,
        lot_size: float,
        signal_id: Optional[int] = None,
        status: str = "OPEN",
        user: str = "system",
    ) -> int:
        """Log a trade execution (or rejection)."""
        with self.Session() as session:
            trade = Trade(
                ticket=ticket,
                symbol=symbol,
                direction=direction,
                entry_price=entry_price,
                lot_size=lot_size,
                signal_id=signal_id,
                status=status,
                created_by=user,
                updated_by=user,
            )
            session.add(trade)
            session.commit()
            return trade.id

    def update_trade(
        self,
        ticket: int,
        exit_price: float,
        pnl: Optional[float] = None,
        drawdown_impact: float = 0.0,
        user: str = "system",
    ) -> None:
        """Update a trade when it is closed. Calculates P&L if not provided."""
        with self.Session() as session:
            stmt = select(Trade).where(Trade.ticket == ticket, Trade.is_deleted.is_(False))
            trade = session.execute(stmt).scalar_one_or_none()
            if trade:
                trade.exit_price = exit_price
                if pnl is not None:
                    trade.pnl = pnl
                else:
                    # Basic P&L calculation for XAUUSD (1 lot = 100 oz)
                    contract_size = 100
                    trade.pnl = (
                        (exit_price - trade.entry_price)
                        * trade.direction
                        * trade.lot_size
                        * contract_size
                    )
                trade.drawdown_impact = drawdown_impact
                trade.status = "CLOSED"
                trade.updated_by = user
                trade.updated_at = datetime.now(timezone.utc)
                session.commit()
            else:
                logger.warning("Trade with ticket %d not found for update.", ticket)

    def get_trade_by_ticket(self, ticket: int) -> Optional[Trade]:
        """Retrieve trade details by ticket ID."""
        with self.Session() as session:
            stmt = select(Trade).where(Trade.ticket == ticket, Trade.is_deleted.is_(False))
            return session.execute(stmt).scalar_one_or_none()

    def log_risk_event(
        self,
        event_type: str,
        description: str,
        symbol: Optional[str] = None,
        signal_id: Optional[int] = None,
        user: str = "system",
    ) -> None:
        """Log a risk-related event."""
        with self.Session() as session:
            event = RiskEvent(
                event_type=event_type,
                description=description,
                symbol=symbol,
                signal_id=signal_id,
                created_by=user,
                updated_by=user,
            )
            session.add(event)
            session.commit()

    def read_performance_report(self, user: str = "system") -> Dict[str, float]:
        """
        Calculate key performance metrics from closed trades.
        Returns Sharpe Ratio, Profit Factor, and Max Drawdown.
        """
        with self.Session() as session:
            stmt = select(Trade).where(Trade.status == "CLOSED", Trade.is_deleted.is_(False))
            trades = session.execute(stmt).scalars().all()
            if not trades:
                return {
                    "sharpe_ratio": 0.0,
                    "profit_factor": 0.0,
                    "max_drawdown": 0.0,
                }

            pnls = np.array([t.pnl for t in trades])

            # Profit Factor
            gross_profit = np.sum(pnls[pnls > 0])
            gross_loss = abs(np.sum(pnls[pnls < 0]))
            profit_factor = gross_profit / gross_loss if gross_loss > 0 else float("inf")

            # Sharpe Ratio (assumes risk-free rate = 0, per-trade returns)
            if len(pnls) > 1:
                avg_ret = np.mean(pnls)
                std_ret = np.std(pnls)
                # Annualization factor for Sharpe Ratio.
                # Assuming daily trades, we use sqrt(252).
                sharpe = (avg_ret / std_ret * np.sqrt(252)) if std_ret > 0 else 0.0
            else:
                sharpe = 0.0

            # Max Drawdown
            equity_curve = np.cumsum(pnls)
            peak = np.maximum.accumulate(equity_curve)
            # Reference drawdown against the peak to find max percentage/absolute dip.
            # Using 0 as initial equity if no previous peak.
            peak = np.maximum(peak, 0)
            drawdown = peak - equity_curve
            max_dd = np.max(drawdown) if len(drawdown) > 0 else 0.0

            metrics = {
                "sharpe_ratio": float(sharpe),
                "profit_factor": float(profit_factor),
                "max_drawdown": float(max_dd),
            }

            # Log these metrics to DB
            metric_record = PerformanceMetric(
                sharpe_ratio=metrics["sharpe_ratio"],
                profit_factor=metrics["profit_factor"],
                max_drawdown=metrics["max_drawdown"],
                total_trades=len(trades),
                win_rate=float(np.sum(pnls > 0) / len(pnls)),
                created_by=user,
                updated_by=user,
            )
            session.add(metric_record)
            session.commit()

            return metrics

    def soft_delete_trade(self, ticket: int, user: str = "system") -> None:
        """Soft delete a trade."""
        with self.Session() as session:
            stmt = select(Trade).where(Trade.ticket == ticket, Trade.is_deleted.is_(False))
            trade = session.execute(stmt).scalar_one_or_none()
            if trade:
                trade.is_deleted = True
                trade.deleted_at = datetime.now(timezone.utc)
                trade.updated_by = user
                session.commit()
