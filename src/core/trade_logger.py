from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Any, Dict, Optional

import numpy as np
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    create_engine,
    event,
    Index,
)
from sqlalchemy.engine import Engine
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship, sessionmaker
from sqlalchemy.pool import QueuePool

Base = declarative_base()
logger = logging.getLogger(__name__)


class AuditMixin:
    """Audit columns as per DATABASE_STANDARDS.md."""

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    updated_at = Column(
        DateTime,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    is_deleted = Column(Boolean, default=False)


class ModelSignal(Base, AuditMixin):
    """Logs every signal generated by the AI models."""

    __tablename__ = "model_signals"
    __table_args__ = (Index("idx_signal_symbol_timestamp", "symbol", "timestamp"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    symbol = Column(String(20), nullable=False)
    direction = Column(Integer, nullable=False)  # +1 buy, -1 sell, 0 hold
    entry_price = Column(Float, nullable=False)
    stop_loss = Column(Float)
    take_profit = Column(Float)
    lot_size = Column(Float)
    algorithm = Column(String(50))
    confidence = Column(Float)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    # Relationship
    trade = relationship("Trade", back_populates="signal", uselist=False)


class Trade(Base, AuditMixin):
    """Logs every executed trade."""

    __tablename__ = "trades"
    __table_args__ = (Index("idx_trade_symbol_status_created", "symbol", "status", "created_at"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    ticket = Column(Integer, unique=True, index=True)
    symbol = Column(String(20), nullable=False)
    direction = Column(Integer, nullable=False)
    entry_price = Column(Float, nullable=False)
    exit_price = Column(Float)
    lot_size = Column(Float, nullable=False)
    pnl = Column(Float, default=0.0)
    drawdown_impact = Column(Float)  # impact on total drawdown
    status = Column(String(20), default="OPEN")  # OPEN, CLOSED, CANCELLED

    signal_id = Column(Integer, ForeignKey("model_signals.id"))
    signal = relationship("ModelSignal", back_populates="trade")


class RiskEvent(Base, AuditMixin):
    """Logs risk management events (rejections, circuit breakers)."""

    __tablename__ = "risk_events"
    __table_args__ = (Index("idx_risk_event_type_symbol", "event_type", "symbol"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    event_type = Column(String(50), nullable=False)
    description = Column(Text)
    symbol = Column(String(20))

    signal_id = Column(Integer, ForeignKey("model_signals.id"), nullable=True)


class PerformanceMetric(Base, AuditMixin):
    """Periodic performance snapshots."""

    __tablename__ = "performance_metrics"
    __table_args__ = (Index("idx_perf_timestamp", "timestamp"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc))
    sharpe_ratio = Column(Float)
    profit_factor = Column(Float)
    max_drawdown = Column(Float)
    total_trades = Column(Integer)
    win_rate = Column(Float)


class TradeLogger:
    """Enterprise trade logging interface."""

    def __init__(self, db_url: str = "sqlite:///trades.db") -> None:
        engine_args = {
            "poolclass": QueuePool,
            "pool_size": 20,
            "max_overflow": 40,
            "pool_pre_ping": True,
            "pool_recycle": 3600,
        }

        if "sqlite" in db_url:
            # SQLite doesn't support pool_size/max_overflow if it's :memory: or default StaticPool
            # But here we are using QueuePool.
            engine_args["connect_args"] = {"check_same_thread": False}

        self.engine = create_engine(db_url, **engine_args)

        if "sqlite" in db_url:

            @event.listens_for(Engine, "connect")
            def set_sqlite_pragma(dbapi_connection, connection_record):
                cursor = dbapi_connection.cursor()
                cursor.execute("PRAGMA foreign_keys=ON")
                cursor.execute("PRAGMA journal_mode=WAL")
                cursor.execute("PRAGMA synchronous=NORMAL")
                cursor.close()

        Base.metadata.create_all(self.engine)
        self.Session = sessionmaker(bind=self.engine)

    def log_signal(self, signal_data: Dict[str, Any]) -> int:
        """Log a new model signal and return its ID."""
        with self.Session() as session:
            with session.begin():
                signal = ModelSignal(
                    symbol=signal_data["symbol"],
                    direction=signal_data["direction"],
                    entry_price=signal_data["entry_price"],
                    stop_loss=signal_data.get("stop_loss"),
                    take_profit=signal_data.get("take_profit"),
                    lot_size=signal_data.get("lot_size"),
                    algorithm=signal_data.get("algorithm"),
                    confidence=signal_data.get("confidence"),
                    timestamp=signal_data.get("timestamp", datetime.now(timezone.utc)),
                )
                session.add(signal)
            return signal.id

    def log_trade(
        self,
        ticket: int,
        symbol: str,
        direction: int,
        entry_price: float,
        lot_size: float,
        signal_id: Optional[int] = None,
        status: str = "OPEN",
    ) -> int:
        """Log a trade execution."""
        with self.Session() as session:
            with session.begin():
                trade = Trade(
                    ticket=ticket,
                    symbol=symbol,
                    direction=direction,
                    entry_price=entry_price,
                    lot_size=lot_size,
                    signal_id=signal_id,
                    status=status,
                )
                session.add(trade)
            return trade.id

    def update_trade(
        self,
        ticket: int,
        exit_price: float,
        pnl: Optional[float] = None,
        drawdown_impact: float = 0.0,
    ) -> None:
        """Update a trade when it is closed. Calculates P&L if not provided."""
        with self.Session() as session:
            with session.begin():
                trade = (
                    session.query(Trade)
                    .filter(Trade.ticket == ticket, Trade.is_deleted == False)
                    .first()
                )
                if trade:
                    trade.exit_price = exit_price
                    if pnl is not None:
                        trade.pnl = pnl
                    else:
                        # Basic P&L calculation: (exit - entry) * direction * lot_size * contract_size
                        # For XAUUSD, contract size is often 100.
                        contract_size = 100
                        trade.pnl = (
                            (exit_price - trade.entry_price)
                            * trade.direction
                            * trade.lot_size
                            * contract_size
                        )
                    trade.drawdown_impact = drawdown_impact
                    trade.status = "CLOSED"
                else:
                    logger.warning("Trade with ticket %d not found for update.", ticket)

    def get_trade_by_ticket(self, ticket: int) -> Optional[Trade]:
        """Retrieve trade details by ticket ID."""
        with self.Session() as session:
            return (
                session.query(Trade)
                .filter(Trade.ticket == ticket, Trade.is_deleted == False)
                .first()
            )

    def log_risk_event(
        self,
        event_type: str,
        description: str,
        symbol: Optional[str] = None,
        signal_id: Optional[int] = None,
    ) -> None:
        """Log a risk-related event."""
        with self.Session() as session:
            with session.begin():
                event = RiskEvent(
                    event_type=event_type,
                    description=description,
                    symbol=symbol,
                    signal_id=signal_id,
                )
                session.add(event)

    def read_performance_report(self) -> Dict[str, float]:
        """
        Calculate key performance metrics from closed trades.
        Returns Sharpe Ratio, Profit Factor, and Max Drawdown.
        """
        with self.Session() as session:
            with session.begin():
                trades = (
                    session.query(Trade)
                    .filter(Trade.status == "CLOSED", Trade.is_deleted == False)
                    .all()
                )
                if not trades:
                    return {
                        "sharpe_ratio": 0.0,
                        "profit_factor": 0.0,
                        "max_drawdown": 0.0,
                    }

                pnls = np.array([t.pnl for t in trades])

                # Profit Factor
                gross_profit = np.sum(pnls[pnls > 0])
                gross_loss = abs(np.sum(pnls[pnls < 0]))
                profit_factor = (
                    gross_profit / gross_loss if gross_loss > 0 else float("inf")
                )

                # Sharpe Ratio (assumes risk-free rate = 0, per-trade returns)
                if len(pnls) > 1:
                    avg_ret = np.mean(pnls)
                    std_ret = np.std(pnls)
                    sharpe = (avg_ret / std_ret * np.sqrt(252)) if std_ret > 0 else 0.0
                else:
                    sharpe = 0.0

                # Max Drawdown
                equity_curve = np.cumsum(pnls)
                peak = np.maximum.accumulate(equity_curve)
                drawdown = peak - equity_curve
                max_dd = np.max(drawdown) if len(drawdown) > 0 else 0.0

                metrics = {
                    "sharpe_ratio": float(sharpe),
                    "profit_factor": float(profit_factor),
                    "max_drawdown": float(max_dd),
                }

                # Optionally log these metrics to DB
                metric_record = PerformanceMetric(
                    sharpe_ratio=metrics["sharpe_ratio"],
                    profit_factor=metrics["profit_factor"],
                    max_drawdown=metrics["max_drawdown"],
                    total_trades=len(trades),
                    win_rate=float(np.sum(pnls > 0) / len(pnls)),
                )
                session.add(metric_record)

            return metrics
